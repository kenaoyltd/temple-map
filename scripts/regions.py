"""対象地域(region.txt / 環境変数 REGION)の読み方。

書ける値:
  全国
  都道府県名           例: 群馬県
  地方名               例: 関東 / 東北 / 中部 / 近畿(関西)/ 中国 / 四国 / 九州
  都道府県をいくつか   例: 東京都,神奈川県,埼玉県(「、」やスペース区切りでも可)
"""
import re

PREFS = ("北海道 青森県 岩手県 宮城県 秋田県 山形県 福島県 茨城県 栃木県 群馬県 埼玉県 千葉県 東京都 神奈川県 新潟県 富山県 石川県 福井県 "
         "山梨県 長野県 岐阜県 静岡県 愛知県 三重県 滋賀県 京都府 大阪府 兵庫県 奈良県 和歌山県 鳥取県 島根県 岡山県 広島県 山口県 "
         "徳島県 香川県 愛媛県 高知県 福岡県 佐賀県 長崎県 熊本県 大分県 宮崎県 鹿児島県 沖縄県").split()

BLOCKS = {
    "北海道": ["北海道"],
    "東北": ["青森県", "岩手県", "宮城県", "秋田県", "山形県", "福島県"],
    "関東": ["茨城県", "栃木県", "群馬県", "埼玉県", "千葉県", "東京都", "神奈川県"],
    "中部": ["新潟県", "富山県", "石川県", "福井県", "山梨県", "長野県", "岐阜県", "静岡県", "愛知県"],
    "近畿": ["三重県", "滋賀県", "京都府", "大阪府", "兵庫県", "奈良県", "和歌山県"],
    "関西": ["滋賀県", "京都府", "大阪府", "兵庫県", "奈良県", "和歌山県"],
    "中国": ["鳥取県", "島根県", "岡山県", "広島県", "山口県"],
    "四国": ["徳島県", "香川県", "愛媛県", "高知県"],
    "九州": ["福岡県", "佐賀県", "長崎県", "熊本県", "大分県", "宮崎県", "鹿児島県", "沖縄県"],
}


def short(p):
    return p[:-1] if len(p) >= 3 and p[-1] in "都府県" else p


def region_prefs(region):
    """都道府県のリストを返す。全国なら None。分からない名前はエラー。"""
    r = (region or "").strip()
    if r in ("", "全国"):
        return None
    key = re.sub(r"(地方|地域)$", "", r)
    if key in BLOCKS:
        return list(BLOCKS[key])
    out = []
    for part in re.split(r"[,、，\s・]+", r):
        if not part:
            continue
        hit = next((p for p in PREFS if part in (p, short(p))), None)
        if not hit:
            raise RuntimeError(f"対象地域の書き方が分かりません: 「{part}」(都道府県名、地方名、または 全国)")
        if hit not in out:
            out.append(hit)
    return out


def pref_in_text(text):
    """住所などの文字列の先頭から都道府県を判定する(無ければ空文字)。"""
    a = re.sub(r"^(〒?\s*\d{3}-?\d{4}\s*|日本[、,\s]*)", "", text or "")
    for p in PREFS:
        if a.startswith(p):
            return p
    return ""
